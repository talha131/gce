/**
 * Memento Database Script: Daily Attendance Creator (Advanced)
 *
 * This script checks for students missing from today's attendance
 * and creates records only for them.
 */

// Helper function to check if two dates fall on the same calendar day.
function isSameDay(d1, d2) {
  if (!d1 || !d2) return false;
  return d1.toDateString() === d2.toDateString();
}

// --- Main Script Logic ---

const allEntries = lib().entries();
const currentDate = new Date();

// 1. Filter all library entries to get only the ones created today.
const todaysEntries = Array.from(allEntries).filter((entry) => {
  const entryDate = entry.field("Date");
  return isSameDay(currentDate, entryDate);
});

// 2. Create a Set of student IDs that are already recorded for today for fast checking.
// We get the ID from the "Seat" field, as that's where it's stored.
const recordedStudentIds = new Set(
  todaysEntries.map((entry) => entry.field("Seat")),
);

// 3. Filter the main `students` list to find who is missing.
// A student is missing if their ID is NOT in the `recordedStudentIds` Set.
const missingStudents = students.filter(
  (student) => !recordedStudentIds.has(student.id),
);

// 4. If there are any missing students, create entries only for them.
if (missingStudents.length > 0) {
  message(
    `Found ${missingStudents.length} missing students for today. Creating records...`,
  );

  // Get the day of the month (0-30) to select the correct number set.
  // This is calculated ONCE outside the loop for better performance.
  const dayIndex = currentDate.getDate() - 1;
  const numberSetForToday = randomNumbers[dayIndex];

  // Safety check: if there's no number set for today, log an error and stop.
  if (!numberSetForToday) {
    log(`Error: No number set found for day index ${dayIndex}.`);
  } else {
    missingStudents.forEach((student) => {
      // To get a consistent number, find the student's original index in the main list.
      const studentIndex = students.findIndex((s) => s.id === student.id);

      const newEntry = {
        Date: currentDate,
        Name: student.name,
        Seat: student.id,
      };

      // Assign the random number only if the student and number exist.
      if (
        studentIndex !== -1 &&
        numberSetForToday[studentIndex] !== undefined
      ) {
        newEntry["Random Number"] = numberSetForToday[studentIndex];
      } else {
        // Handle cases where the number might be missing for an index.
        newEntry["Random Number"] = null;
        log(`Warning: Could not find a random number for ${student.name}.`);
      }

      try {
        lib().create(newEntry);
      } catch (e) {
        log(`Error creating entry for ${student.name}: ${e}`);
      }
    });

    message(`Done! Added ${missingStudents.length} new records. ✅`);
  }
} else {
  message(
    "All student records for today are already present. No action needed. 👍",
  );
}
